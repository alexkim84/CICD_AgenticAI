function processmodel(pm)
%PROCESSMODEL Define the Jenkins verification process for crs_controller.

arguments
    pm padv.ProcessModel
end

pm.DefaultOutputDirectory = fullfile("$PROJECTROOT$", "artifacts", "process-advisor");
junitRunToken = string(getenv("CI_RUN_TOKEN"));
if strlength(junitRunToken) == 0
    pm.JUnitReportPath = fullfile("$DEFAULTOUTPUTDIR$", "junit");
else
    pm.JUnitReportPath = fullfile("$DEFAULTOUTPUTDIR$", "junit", ...
        junitRunToken);
end

projectRoot = string(currentProject().RootFolder);
modelQuery = padv.builtin.query.FindFileWithAddress( ...
    Type="sl_model_file", ...
    Path=fullfile(projectRoot, "models", "crs_controller.slx"), ...
    Name="CruiseController");
pm.addQuery(modelQuery);
milTestQuery = padv.builtin.query.FindFileWithAddress( ...
    Type="sl_test_file", ...
    Path=fullfile(projectRoot, "tests", "test_file", ...
    "crs_controller_requirements_MIL.mldatx"), ...
    Name="CruiseRequirementsMILTests");
pm.addQuery(milTestQuery);
silTestQuery = padv.builtin.query.FindFileWithAddress( ...
    Type="sl_test_file", ...
    Path=fullfile(projectRoot, "tests", "test_file", ...
    "crs_controller_mil_sil_equivalence_tests.mldatx"), ...
    Name="CruiseMILSILEquivalenceTests");
pm.addQuery(silTestQuery);

compileTask = padv.Task("CI.CompileModel");
compileTask.Title = "Compile Cruise Controller";
compileTask.DescriptionText = ...
    "Load and update crs_controller and record its interface and checksum.";
compileTask.RequiredIterationArtifactType = "sl_model_file";
compileTask.IterationQuery = modelQuery;
compileTask.addInputQueries(padv.builtin.query.GetIterationArtifact);
compileTask.Action = @ci_task_compile_model;
compileTask.OutputDirectory = fullfile("$DEFAULTOUTPUTDIR$", "compile");
compileTask.AlwaysRun = true;
pm.addTask(compileTask);

interfaceTask = padv.Task("CI.CheckModelInterface");
interfaceTask.Title = "Check Model Interface";
interfaceTask.DescriptionText = ...
    "Verify the expected 11 inputs and 5 outputs of crs_controller.";
interfaceTask.RequiredIterationArtifactType = "sl_model_file";
interfaceTask.IterationQuery = modelQuery;
interfaceTask.addInputQueries(padv.builtin.query.GetIterationArtifact);
interfaceTask.Action = @ci_task_check_interface;
interfaceTask.OutputDirectory = fullfile("$DEFAULTOUTPUTDIR$", "interface");
pm.addTask(interfaceTask);
interfaceTask.dependsOn(compileTask);

requirementsTask = padv.Task("CI.CheckRequirementsTraceability");
requirementsTask.Title = "Check Requirements Traceability";
requirementsTask.DescriptionText = ...
    "Load the requirement and link sets and verify that traceability data exists.";
requirementsTask.RequiredIterationArtifactType = "sl_model_file";
requirementsTask.IterationQuery = modelQuery;
requirementsTask.addInputQueries( ...
    padv.builtin.query.GetIterationArtifact);
requirementsTask.InputDependencyQuery = ...
    padv.builtin.query.GetDependentArtifacts( ...
    IncludeRequirementLinkFiles=true);
requirementsTask.Action = @ci_task_check_requirements;
requirementsTask.OutputDirectory = fullfile("$DEFAULTOUTPUTDIR$", "requirements");
pm.addTask(requirementsTask);

standardsTask = padv.builtin.task.RunModelStandards( ...
    Name="CI.ModelAdvisor", ...
    Title="Model Advisor Standards", ...
    IterationQuery=modelQuery);
standardsTask.CheckIDList = readConfiguredCheckIDs();
standardsTask.DisplayResults = "Details";
standardsTask.ReportFormat = "html";
standardsTask.ReportPath = fullfile("$DEFAULTOUTPUTDIR$", ...
    "model-advisor");
standardsTask.ReportName = "ModelAdvisorReport";
pm.addTask(standardsTask);
standardsTask.dependsOn(interfaceTask);

designErrorTask = padv.builtin.task.DetectDesignErrors( ...
    Name="CI.DesignErrorDetection", ...
    Title="Design Error and Dead Logic Detection", ...
    IterationQuery=modelQuery);
designErrorTask.DetectDeadLogic = "on";
designErrorTask.DetectActiveLogic = "off";
designErrorTask.GenerateReport = true;
designErrorTask.DisplayReport = "off";
designErrorTask.MaxProcessTime = readSettings(). ...
    designVerifierMaxProcessTimeSeconds;
designErrorTask.Options = ["summary" "objectives" "objects"];
designErrorTask.ReportFormat = "HTML";
designErrorTask.OutputDirectory = fullfile("$DEFAULTOUTPUTDIR$", ...
    "design-error");
designErrorTask.ReportFilePath = fullfile("$DEFAULTOUTPUTDIR$", ...
    "design-error", "SLDVReport", "crs_controller_DeadLogic");
pm.addTask(designErrorTask);
designErrorTask.dependsOn(standardsTask);

requirementsTask.dependsOn(designErrorTask);

milTask = pm.addTask("CI.RequirementsMIL", ...
    Title="Requirements-Based MIL Tests", ...
    DescriptionText="Run requirements-linked MIL tests and export evidence.", ...
    IterationQuery=modelQuery, ...
    InputQueries=[padv.builtin.query.GetIterationArtifact, milTestQuery], ...
    InputDependencyQuery=padv.builtin.query.GetDependentArtifacts( ...
    IncludeRequirementLinkFiles=true), ...
    Action=@ci_task_run_mil_tests, ...
    Licenses="simulink_test", ...
    OutputDirectory=fullfile("$DEFAULTOUTPUTDIR$", ...
    "requirements-mil"));
milTask.dependsOn(requirementsTask);

silTask = pm.addTask("CI.MILSILEquivalence", ...
    Title="MIL/SIL Equivalence Tests", ...
    DescriptionText="Run back-to-back MIL and SIL equivalence tests.", ...
    IterationQuery=modelQuery, ...
    InputQueries=[padv.builtin.query.GetIterationArtifact, silTestQuery], ...
    Action=@ci_task_run_sil_tests, ...
    Licenses="simulink_test", ...
    OutputDirectory=fullfile("$DEFAULTOUTPUTDIR$", "mil-sil"));
silTask.dependsOn(milTask);

codeTask = padv.builtin.task.GenerateCode( ...
    Name="CI.GenerateCode", ...
    Title="Generate Controller Code", ...
    IterationQuery=modelQuery);
codeTask.GenerateCodeOnly = true;
codeTask.ForceTopModelBuild = true;
codeTask.GenerateTraceReport = true;
codeTask.TraceReportName = "crs_controller_traceability";
pm.addTask(codeTask);
codeTask.dependsOn(silTask);
end

function checkIDs = readConfiguredCheckIDs()
projectRoot = currentProject().RootFolder;
configPath = fullfile(projectRoot, "data", ...
    "auto_modeling_guidelines.json");
config = jsondecode(fileread(configPath));
nodes = config.Tree;
selected = arrayfun(@(node) logical(node.check) && ...
    logical(node.enable) && ~isempty(node.checkid), nodes);
checkIDs = string({nodes(selected).checkid});
end

function settings = readSettings()
projectRoot = currentProject().RootFolder;
settingsPath = fullfile(projectRoot, "config", ...
    "process_advisor_settings.json");
settings = jsondecode(fileread(settingsPath));
end
